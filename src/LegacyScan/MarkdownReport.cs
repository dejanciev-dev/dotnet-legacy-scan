using System.Globalization;
using System.Text;

namespace LegacyScan;

/// <summary>
/// Short Markdown summary for pull requests and CI, e.g. <c>--md "$GITHUB_STEP_SUMMARY"</c> in GitHub Actions.
/// The HTML report stays the full version.
/// </summary>
public static class MarkdownReport
{
    public static string Render(ScanReport r, ReportOptions o)
    {
        var sb = new StringBuilder();
        string Days(double h) => Cli.Days(h, o);
        var title = Path.GetFileName(r.Input.TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar));

        sb.AppendLine($"## Migration readiness: {Md(title)}").AppendLine();
        sb.AppendLine("| Difficulty | Estimated effort | Projects | Code | Findings |");
        sb.AppendLine("|---|---|---|---|---|");
        sb.AppendLine($"| **{Md(r.Difficulty)}** ({r.Score}/100) | {Days(r.EstimatedHoursLow)}–{Days(r.EstimatedHoursHigh)} developer days | " +
                      $"{r.Projects.Count} ({r.Projects.Count(p => p.IsModernAlready)} already modern) | {r.TotalLoc.ToString("N0", CultureInfo.InvariantCulture)} lines | " +
                      $"{r.CountBySeverity(Severity.Blocker)} blocker · {r.CountBySeverity(Severity.Major)} major · {r.CountBySeverity(Severity.Minor)} minor |");
        sb.AppendLine();
        foreach (var w in r.Warnings) sb.AppendLine($"> ⚠ {Md(w)}").AppendLine();

        var blockers = r.BlockerGroups();
        if (blockers.Count > 0)
        {
            sb.AppendLine("### What makes this migration hard").AppendLine();
            foreach (var (rule, count, projects) in blockers)
                sb.AppendLine($"- **{Md(rule.Title)}** ×{count} in {Md(string.Join(", ", projects))}");
            sb.AppendLine();
        }

        sb.AppendLine("### Projects (recommended migration order)").AppendLine();
        sb.AppendLine("| # | Project | Type | Target | Worst | Base effort (days) |");
        sb.AppendLine("|---|---|---|---|---|---|");
        var byName = r.Projects.GroupBy(p => p.Name, StringComparer.OrdinalIgnoreCase).ToDictionary(g => g.Key, g => g.First(), StringComparer.OrdinalIgnoreCase);
        var n = 0;
        foreach (var name in r.MigrationOrder)
        {
            if (!byName.TryGetValue(name.Replace(" (circular reference)", ""), out var p)) continue;
            var worst = p.IsModernAlready && p.Findings.Count == 0 ? "OK" : p.WorstSeverity.ToString();
            sb.AppendLine($"| {++n} | {Md(name)} | {Md(HtmlReport.KindLabel(p.Kind))} | `{Md(p.TargetFramework)}` | {worst} | {(p.EstimatedHours > 0 ? Days(p.EstimatedHours) : "–")} |");
        }
        sb.AppendLine();
        sb.AppendLine($"<sub>Generated by [dotnet-legacy-scan](https://github.com/dejanciev-dev/dotnet-legacy-scan) {Md(r.ToolVersion)}. " +
                      "A rough estimate for planning, not a quote; see the HTML report for findings and guidance.</sub>");
        return sb.ToString();
    }

    /// <summary>Keeps names from breaking tables or turning into HTML.</summary>
    private static string Md(string s) => s.Replace("|", "\\|").Replace("<", "&lt;").Replace(">", "&gt;");
}
